// ModeByID ищет режим по id (регистронезависимо).
func ModeByID(id string) (Mode, bool) {
	key := strings.ToLower(strings.TrimSpace(id))
	for _, m := range Modes {
		if strings.ToLower(m.ID) == key {
			return m, true
		}
	}
	return Mode{}, false
}

// buildSystemPrompt собирает системный промпт под направление, тему и режим.
func buildSystemPrompt(d curriculum.Direction, t curriculum.Topic, m Mode, mastery int, lang string) string {
	var b strings.Builder
	b.WriteString("Ты — персональный технический ментор и тренер по собеседованиям. Ученик — бэкенд-инженер, готовится к собеседованиям уровня middle/senior.\n\n")

	b.WriteString("ОБЩИЕ ПРАВИЛА ОБУЧЕНИЯ (соблюдай всегда):\n")
	b.WriteString("- Объясняй по-русски, простыми словами, без воды.\n")
	b.WriteString("- СНАЧАЛА задавай наводящие вопросы, а не выдавай ответ.\n")
	b.WriteString("- НЕ выдавай решение алгоритма/задачи сразу — веди ученика к нему вопросами и подсказками.\n")
	b.WriteString("- Оценивай ответ по трём осям: ТОЧНОСТЬ (факты), ГЛУБИНА (почему так устроено), ПРАКТИКА (где применить).\n")
	b.WriteString("- Не считай тему изученной после одного верного ответа: проверяй повторно и с разных сторон.\n")
	b.WriteString("- Короткие порции текста; не превращай ответ в лекцию.\n")
	if lang != "" && lang != "ru" {
		b.WriteString(fmt.Sprintf("- Язык объяснений: %s.\n", lang))
	}
	b.WriteString("\n")

	b.WriteString(fmt.Sprintf("НАПРАВЛЕНИЕ: %s\n", d.Title))
	if strings.TrimSpace(d.Goal) != "" {
		b.WriteString(fmt.Sprintf("ЦЕЛЬ НАПРАВЛЕНИЯ: %s\n", d.Goal))
	}
	b.WriteString(fmt.Sprintf("ТЕМА: %s\n", t.Title))
	if len(t.KeyPoints) > 0 {
		b.WriteString("Опорные тезисы темы (не зачитывай списком, используй для вопросов):\n")
		for _, kp := range t.KeyPoints {
			b.WriteString("  - " + kp + "\n")
		}
	}
	if strings.TrimSpace(t.Material) != "" {
		b.WriteString(fmt.Sprintf("Конспект по теме в репозитории: %s (можешь ссылаться как на материал для повторения).\n", t.Material))
	}
	b.WriteString(fmt.Sprintf("Текущий уровень ученика по теме: %d/5.\n\n", mastery))

	b.WriteString("РЕЖИМ СЕССИИ: " + m.Title + "\n")
	b.WriteString(m.Rules + "\n\n")

	b.WriteString("ОЦЕНКА И ФОРМАТ.\n")
	if m.Evaluating {
		b.WriteString("После КАЖДОГО ответа ученика завершай сообщение отдельной строкой строго вида `[[SCORE:n]]`, где n — целое 0..5 (0 — неверно, 3 — частично, 5 — отлично). Эта строка нужна системе; не объясняй её ученику.\n")
	} else {
		b.WriteString("Этот режим не оценивается: строку [[SCORE:...]] не добавляй.\n")
	}
	b.WriteString("Если ученик задаёт служебные команды (/done, /help, /skip) — обрабатывает система, не отвечай на них как на материал.\n")
	return b.String()
}

// openingInstruction — стартовое сообщение, чтобы ментор открыл сессию.
func openingInstruction(m Mode) string {
	switch m.ID {
	case "interview":
		return "Начни мок-интервью: поприветствуй и задай ПЕРВЫЙ вопрос по теме — только один вопрос, без подсказок."
	case "learn":
		return "Начни занятие: кратко в одном предложении обозначь план и задай первый наводящий вопрос по теме, чтобы понять текущий уровень ученика. Готового ответа не давай."
	case "mistake":
		return "Предложи ученику описать ошибку или баг по теме: что случилось, что ожидалось, что получилось. Задай первый уточняющий вопрос."
	case "check":
		return "Попроси ученика прислать его решение задачи по теме (код/схему/псевдокод) и кратко опиши, что будешь оценивать. Пока решение ученика не получено — правильного ответа не давай."
	case "prod":
		return "Опиши короткий реальный прод-сценарий по теме (1–2 предложения) и попроси ученика предложить первые шаги диагностики. Решения не подсказывай."
	case "review":
		return "Начни повторение слабой темы: задай первый короткий вопрос на припоминание. Подсказок не давай."
	default:
		return "Начни сессию по теме наводящим вопросом. Готового ответа не давай."
	}
}
